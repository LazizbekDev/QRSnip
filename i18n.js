let qrsnipLocale = "en";

const QRSNIP_RTL = new Set(["ar", "fa"]);

/**
 * Map browser / Chrome UI language to a supported locale.
 * @param {string} raw
 * @returns {string}
 */
function normalizeLocale(raw) {
  const s = String(raw || "en").toLowerCase().replace(/_/g, "-");
  if (s.startsWith("zh")) return "zh";
  if (s.startsWith("ja")) return "ja";
  if (s.startsWith("ru")) return "ru";
  if (s.startsWith("de")) return "de";
  if (s.startsWith("uz")) return "uz";
  if (s.startsWith("hi")) return "hi";
  if (s.startsWith("id")) return "id";
  if (s.startsWith("th")) return "th";
  if (s.startsWith("fr")) return "fr";
  if (s.startsWith("es")) return "es";
  if (s.startsWith("ar")) return "ar";
  if (s.startsWith("fa") || s.startsWith("per")) return "fa";
  if (s.startsWith("vi")) return "vi";
  if (s.startsWith("en")) return "en";
  const base = s.split("-")[0];
  if (QRSNIP_SUPPORTED.includes(base)) return base;
  return "en";
}

/**
 * @returns {string}
 */
function detectBrowserLocale() {
  try {
    if (typeof chrome !== "undefined" && chrome.i18n?.getUILanguage) {
      return normalizeLocale(chrome.i18n.getUILanguage());
    }
  } catch (_) {}
  const nav = (typeof navigator !== "undefined" && (navigator.languages?.[0] || navigator.language)) || "en";
  return normalizeLocale(nav);
}

/**
 * @param {"auto"|string} preference
 * @returns {string} resolved locale code
 */
function resolveLocale(preference) {
  if (!preference || preference === "auto") return detectBrowserLocale();
  return normalizeLocale(preference);
}

/**
 * @param {"auto"|string} preference
 */
function initI18n(preference) {
  qrsnipLocale = resolveLocale(preference);
  try {
    document.documentElement.lang = qrsnipLocale === "zh" ? "zh-CN" : qrsnipLocale;
    document.documentElement.dir = QRSNIP_RTL.has(qrsnipLocale) ? "rtl" : "ltr";
    if (document.title) document.title = t("page_title");
  } catch (_) {}
  return qrsnipLocale;
}

/**
 * @returns {string}
 */
function getLocale() {
  return qrsnipLocale;
}

/**
 * Translate key; supports {n} / {name} placeholders.
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 * @returns {string}
 */
function t(key, vars) {
  const table = QRSNIP_STRINGS[qrsnipLocale] || QRSNIP_STRINGS.en;
  let str = table[key] || QRSNIP_STRINGS.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}
